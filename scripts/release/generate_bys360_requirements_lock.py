"""Generate (or ``--check``) requirements.lock, the hash-pinned production lock.

Target: CPython 3.12, Windows x64 (win_amd64), wheels only. The lock is a flat,
hash-pinned list of every package pip resolves for requirements.txt; it is
installed offline from build/wheelhouse by scripts/windows/prepare_bys360_candidate.ps1
and must never be hand-edited.

How a lock is produced:

1. Every pin of the existing lock is kept as a constraint, except the packages
   pinned in requirements.txt and the ones moved with ``--upgrade-package``.
   Nothing else can change version, so a regeneration never drifts silently.
2. ``pip install --dry-run --report`` resolves requirements.txt for the Windows
   target. pip evaluates environment markers on the *host*, so on Linux it drops
   Windows-only dependencies (click -> colorama). The dependency closure is
   therefore recomputed from the report metadata with a fixed Windows marker
   environment; missing packages are resolved in a further pass, packages that
   only a non-Windows host would need are refused.
3. Each package must resolve to a win_amd64 or pure-Python wheel that is not
   yanked, with the sha256 the index publishes. A new package, or a version
   change that requirements.txt or ``--upgrade-package`` does not explain,
   stops the run.
4. The output is deterministic (no date, commit or pip version; ASCII, LF), so
   ``--check`` can regenerate it on Windows CI and require byte equality.

The actual wheel bytes are verified separately: build_bys360_wheelhouse.py
downloads them and compares their sha256 with this lock, and
``pip install --require-hashes`` checks them again.
"""
from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import subprocess
import sys
import tempfile
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.tags import Tag, compatible_tags, cpython_tags
from packaging.utils import (
    InvalidWheelFilename,
    canonicalize_name as _canonicalize_name,
    parse_wheel_filename,
)

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_bys360_wheelhouse import LockFileError, parse_lock  # noqa: E402

PACKAGE = "BYS360_REQUIREMENTS_LOCK_GENERATOR_V1"
INDEX_URL = "https://pypi.org/simple"
REPORT_VERSION = "1"
MAX_PASSES = 3
TARGET_ARGS = (
    "--python-version", "3.12",
    "--platform", "win_amd64",
    "--implementation", "cp",
    "--abi", "cp312",
    "--only-binary=:all:",
)
# Marker values of the production host. platform_release/platform_version are
# deliberately absent: a marker that needs them cannot be decided here and is refused.
WINDOWS_MARKER_ENV: dict[str, str] = {
    "implementation_name": "cpython",
    "implementation_version": "3.12.0",
    "os_name": "nt",
    "platform_machine": "AMD64",
    "platform_python_implementation": "CPython",
    "platform_system": "Windows",
    "python_full_version": "3.12.0",
    "python_version": "3.12",
    "sys_platform": "win32",
}
UNDECIDABLE_MARKER_VARIABLES = ("platform_release", "platform_version")
REQUIREMENT_LINE_RE = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(?P<extras>\[[A-Za-z0-9._,-]+\])?==(?P<version>[A-Za-z0-9][A-Za-z0-9._!+-]*)$")
PIN_RE = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[A-Za-z0-9][A-Za-z0-9._!+-]*)$")
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
SUPPORTED_TAGS: frozenset[Tag] = frozenset(
    [
        *cpython_tags(python_version=(3, 12), abis=["cp312"], platforms=["win_amd64"]),
        *compatible_tags(python_version=(3, 12), interpreter="cp312", platforms=["win_amd64"]),
    ]
)

HEADER = """\
# BYS360 requirements.lock -- GENERATED FILE. DO NOT HAND-EDIT.
#
# Generated by: python scripts/release/generate_bys360_requirements_lock.py
#   Verify (no write):  python scripts/release/generate_bys360_requirements_lock.py --check
#   Move a transitive pin:  ... --upgrade-package NAME==VERSION
# Run it with CPython 3.12. Previous pins are kept as constraints: only requirements.txt
# pins and explicit --upgrade-package pins can change a version.
#
# Target: CPython 3.12, Windows x64 (win_amd64), wheels only (no sdist, no local compiler).
# Environment markers are evaluated for Windows (os_name=nt, sys_platform=win32,
# platform_system=Windows), so Windows-only dependencies such as colorama are included
# even when the generator runs on Linux.
#
# bys360-lock: packages={total} direct={direct} transitive={transitive}
#
# Format: pip's native hash-checking requirements syntax (name==version + one
# --hash=sha256:<digest> of the selected wheel). This is a full, flat lock of the ENTIRE
# resolved graph: every line is pinned and hash-verified, as pip's --require-hashes mode
# requires (https://pip.pypa.io/en/stable/topics/secure-installs/).
#
# Consume with either:
#   pip install --no-index --find-links build/wheelhouse --require-hashes -r requirements.lock  (offline)
#   pip install --require-hashes -r requirements.lock                                           (online)
# build/wheelhouse is produced and hash-verified by scripts/release/build_bys360_wheelhouse.py.
#
# Direct dependencies (pinned in requirements.txt):
"""


def canonicalize_name(name: str) -> str:
    return str(_canonicalize_name(name))


class LockGenerationError(Exception):
    """The lock cannot be generated safely; nothing is written."""


@dataclass(frozen=True)
class DirectRequirement:
    name: str
    extras: frozenset[str]
    version: str


@dataclass
class ResolvedPackage:
    name: str
    version: str
    filename: str
    sha256: str
    requires_dist: list[str] = field(default_factory=list)


def check_interpreter() -> None:
    if sys.implementation.name != "cpython" or sys.version_info[:2] != (3, 12):
        raise LockGenerationError(
            "the lock must be generated with CPython 3.12: pip evaluates python_version markers "
            f"with the running interpreter, not --python-version (running {sys.implementation.name} "
            f"{sys.version_info[0]}.{sys.version_info[1]})"
        )


def read_requirements(path: Path) -> list[DirectRequirement]:
    if not path.is_file():
        raise LockGenerationError(f"requirements file not found: {path}")
    direct: list[DirectRequirement] = []
    seen: set[str] = set()
    for line_no, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        text = raw.split("#", 1)[0].strip()
        if not text:
            continue
        match = REQUIREMENT_LINE_RE.match(text)
        if match is None:
            raise LockGenerationError(
                f"{path}:{line_no}: only exact pins (name[extras]==version, no markers) are supported: {text!r}"
            )
        key = canonicalize_name(match.group("name"))
        if key in seen:
            raise LockGenerationError(f"{path}:{line_no}: duplicate requirement {match.group('name')}")
        seen.add(key)
        extras = match.group("extras")
        direct.append(
            DirectRequirement(
                name=match.group("name"),
                extras=frozenset(e.strip() for e in extras[1:-1].split(",")) if extras else frozenset(),
                version=match.group("version"),
            )
        )
    if not direct:
        raise LockGenerationError(f"{path}: no requirements")
    return direct


def parse_upgrades(values: Sequence[str]) -> dict[str, str]:
    upgrades: dict[str, str] = {}
    for value in values:
        match = PIN_RE.match(value.strip())
        if match is None:
            raise LockGenerationError(f"--upgrade-package must be NAME==VERSION, got {value!r}")
        upgrades[canonicalize_name(match.group("name"))] = match.group("version")
    return upgrades


def build_constraints(
    previous: dict[str, tuple[str, str]], direct: Sequence[DirectRequirement], upgrades: dict[str, str]
) -> list[str]:
    direct_names = {canonicalize_name(d.name) for d in direct}
    for key in upgrades:
        if key in direct_names:
            raise LockGenerationError(f"{key} is pinned in requirements.txt; change it there, not with --upgrade-package")
        if key not in previous:
            raise LockGenerationError(f"--upgrade-package {key}: not in the current lock (new packages are refused)")
    lines = []
    for key in sorted(previous):
        if key in direct_names:
            continue
        name, version = previous[key]
        lines.append(f"{name}=={upgrades.get(key, version)}")
    return lines


def run_pip_resolution(
    requirements: Path, constraints: Path, extra_roots: Iterable[str], report: Path
) -> dict[str, object]:
    cmd = [
        sys.executable, "-m", "pip", "install",
        "--dry-run", "--ignore-installed", "--isolated", "--no-input",
        "--disable-pip-version-check", "--quiet",
        "--index-url", INDEX_URL,
        "--report", str(report),
        "-r", str(requirements),
        "-c", str(constraints),
        *TARGET_ARGS,
        *extra_roots,
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        tail = "\n".join((proc.stderr or proc.stdout).strip().splitlines()[-15:])
        raise LockGenerationError(f"pip resolution failed (exit {proc.returncode}):\n{tail}")
    data = json.loads(report.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("version") != REPORT_VERSION:
        raise LockGenerationError(f"unsupported pip report version: {data.get('version') if isinstance(data, dict) else data!r}")
    return data


def packages_from_report(report: dict[str, object]) -> dict[str, ResolvedPackage]:
    install = report.get("install")
    if not isinstance(install, list):
        raise LockGenerationError("pip report has no install list")
    packages: dict[str, ResolvedPackage] = {}
    for item in install:
        metadata = item["metadata"]
        download = item["download_info"]
        name, version = metadata["name"], metadata["version"]
        if item.get("is_yanked"):
            raise LockGenerationError(f"{name}=={version} is yanked")
        url = download["url"]
        filename = url.rsplit("/", 1)[-1].split("#", 1)[0]
        if not filename.endswith(".whl"):
            raise LockGenerationError(f"{name}=={version}: not a wheel ({filename}); a source build is never accepted")
        try:
            _, _, _, tags = parse_wheel_filename(filename)
        except InvalidWheelFilename as exc:
            raise LockGenerationError(f"{name}=={version}: invalid wheel filename {filename!r}") from exc
        if not tags & SUPPORTED_TAGS:
            raise LockGenerationError(f"{filename}: no tag supported by CPython 3.12 win_amd64")
        sha256 = str(download.get("archive_info", {}).get("hashes", {}).get("sha256", ""))
        if not SHA256_RE.match(sha256):
            raise LockGenerationError(f"{filename}: the index gave no valid sha256 ({sha256!r})")
        packages[canonicalize_name(name)] = ResolvedPackage(
            name=name, version=version, filename=filename, sha256=sha256,
            requires_dist=list(metadata.get("requires_dist") or []),
        )
    return packages


def _marker_applies(marker: Marker | None, extras: frozenset[str]) -> bool:
    if marker is None:
        return True
    text = str(marker)
    for variable in UNDECIDABLE_MARKER_VARIABLES:
        if variable in text:
            raise LockGenerationError(f"marker {text!r} depends on {variable}, which cannot be decided for the target")
    return any(marker.evaluate({**WINDOWS_MARKER_ENV, "extra": extra}) for extra in ("", *sorted(extras)))


def windows_closure(
    direct: Sequence[DirectRequirement], packages: dict[str, ResolvedPackage]
) -> tuple[set[str], set[str]]:
    """Names the Windows target needs, and those among them the report lacks."""
    needed: dict[str, frozenset[str]] = {}
    missing: set[str] = set()
    stack = [(canonicalize_name(d.name), d.extras) for d in direct]
    while stack:
        key, extras = stack.pop()
        if key in needed and extras <= needed[key]:
            continue
        needed[key] = needed.get(key, frozenset()) | extras
        package = packages.get(key)
        if package is None:
            missing.add(key)
            continue
        for spec in package.requires_dist:
            requirement = Requirement(spec)
            if _marker_applies(requirement.marker, needed[key]):
                stack.append((canonicalize_name(requirement.name), frozenset(requirement.extras)))
    return set(needed), missing


def resolve(
    requirements: Path,
    direct: Sequence[DirectRequirement],
    constraints: list[str],
    workdir: Path,
) -> dict[str, ResolvedPackage]:
    constraint_file = workdir / "constraints.txt"
    constraint_file.write_text("\n".join(constraints) + "\n", encoding="utf-8")
    pinned = {canonicalize_name(line.split("==", 1)[0]) for line in constraints}
    extra_roots: list[str] = []
    for attempt in range(1, MAX_PASSES + 1):
        report = run_pip_resolution(requirements, constraint_file, extra_roots, workdir / f"report{attempt}.json")
        packages = packages_from_report(report)
        needed, missing = windows_closure(direct, packages)
        if not missing:
            unexpected = set(packages) - needed
            if unexpected:
                raise LockGenerationError(
                    "the host resolution contains packages the Windows target does not need "
                    f"({', '.join(sorted(unexpected))}); run the generator on Windows"
                )
            return packages
        unpinned = missing - pinned
        if unpinned:
            raise LockGenerationError(
                f"Windows needs {', '.join(sorted(unpinned))}, which the current lock does not pin (new packages are refused)"
            )
        extra_roots = sorted(set(extra_roots) | missing)
    raise LockGenerationError(f"Windows closure still incomplete after {MAX_PASSES} passes")


def check_version_policy(
    packages: dict[str, ResolvedPackage],
    previous: dict[str, tuple[str, str]],
    direct: Sequence[DirectRequirement],
    upgrades: dict[str, str],
) -> None:
    allowed = {canonicalize_name(d.name): d.version for d in direct} | upgrades
    problems = []
    for key, package in sorted(packages.items()):
        if key not in previous:
            problems.append(f"new package {package.name}=={package.version}")
        elif package.version != previous[key][1] and allowed.get(key) != package.version:
            problems.append(f"unapproved version change {package.name} {previous[key][1]} -> {package.version}")
    for key, version in allowed.items():
        if key in packages and packages[key].version != version:
            problems.append(f"{packages[key].name} resolved to {packages[key].version}, expected {version}")
    if problems:
        raise LockGenerationError("; ".join(problems))


def render(packages: dict[str, ResolvedPackage], direct: Sequence[DirectRequirement]) -> str:
    direct_keys = sorted({canonicalize_name(d.name) for d in direct})
    out = [HEADER.format(total=len(packages), direct=len(direct_keys), transitive=len(packages) - len(direct_keys))]
    for key in direct_keys:
        out.append(f"#   {packages[key].name}=={packages[key].version}\n")
    out.append("\n")
    for key in sorted(packages):
        package = packages[key]
        out.append(f"{package.name}=={package.version} \\\n    --hash=sha256:{package.sha256}\n")
    text = "".join(out)
    text.encode("ascii")  # the lock is ASCII-only; non-ASCII metadata would be a surprise worth stopping on
    return text


def generate(requirements: Path, lock: Path, upgrades: dict[str, str]) -> str:
    check_interpreter()
    direct = read_requirements(requirements)
    try:
        previous = {canonicalize_name(r.name): (r.name, r.version) for r in parse_lock(lock)}
    except LockFileError as exc:
        raise LockGenerationError(f"the current lock is required as constraints: {exc}") from exc
    constraints = build_constraints(previous, direct, upgrades)
    with tempfile.TemporaryDirectory(prefix="bys360-lock-") as tmp:
        packages = resolve(requirements, direct, constraints, Path(tmp))
    for d in direct:
        if canonicalize_name(d.name) not in packages:
            raise LockGenerationError(f"{d.name} is missing from the resolution")
    check_version_policy(packages, previous, direct, upgrades)
    return render(packages, direct)


def write_lock(lock: Path, text: str, expected_count: int) -> None:
    tmp = lock.with_name(lock.name + ".tmp")
    with tmp.open("w", encoding="ascii", newline="\n") as handle:
        handle.write(text)
    os.replace(tmp, lock)
    if len(parse_lock(lock)) != expected_count:
        raise LockGenerationError("the written lock does not parse back to the generated package count")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or verify the BYS360 Windows production requirements.lock.")
    parser.add_argument("--root", default=".", help="repository root (default: current directory)")
    parser.add_argument("--requirements", default=None, help="default: <root>/requirements.txt")
    parser.add_argument("--lock", default=None, help="default: <root>/requirements.lock")
    parser.add_argument("--upgrade-package", action="append", default=[], metavar="NAME==VERSION",
                        help="move a pin that requirements.txt does not set (repeatable)")
    parser.add_argument("--check", action="store_true", help="regenerate in memory and fail if the lock differs")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    requirements = Path(args.requirements).resolve() if args.requirements else root / "requirements.txt"
    lock = Path(args.lock).resolve() if args.lock else root / "requirements.lock"
    try:
        if args.check and args.upgrade_package:
            raise LockGenerationError("--upgrade-package cannot be combined with --check")
        text = generate(requirements, lock, parse_upgrades(args.upgrade_package))
        count = text.count("\n    --hash=sha256:")
        if args.check:
            current = lock.read_text(encoding="ascii").replace("\r\n", "\n")
            if current != text:
                diff = difflib.unified_diff(
                    current.splitlines(keepends=True), text.splitlines(keepends=True),
                    "requirements.lock (committed)", "requirements.lock (regenerated)",
                )
                sys.stdout.writelines(diff)
                print(json.dumps({"ok": False, "package": PACKAGE, "error": "requirements.lock is not what the generator produces"}))
                return 1
            print(json.dumps({"ok": True, "package": PACKAGE, "mode": "check", "packages": count}))
            return 0
        write_lock(lock, text, count)
        print(json.dumps({"ok": True, "package": PACKAGE, "mode": "write", "packages": count, "lock": str(lock)}))
        return 0
    except LockGenerationError as exc:
        print(json.dumps({"ok": False, "package": PACKAGE, "error": str(exc)}, ensure_ascii=False))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
